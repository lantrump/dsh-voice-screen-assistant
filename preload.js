const { contextBridge, ipcRenderer } = require('electron');
let _cnv = null;
try { const opencc = require('opencc-js'); _cnv = opencc.Converter({ from: 'tw', to: 'cn' }); } catch(e) { console.error('opencc load fail:', e && e.message); }
contextBridge.exposeInMainWorld('dsh', {
  capture: (opts) => ipcRenderer.invoke('capture', opts),
  sources: () => ipcRenderer.invoke('sources'),
  screenSize: () => ipcRenderer.invoke('screen-size'),
  getPos: () => ipcRenderer.invoke('get-pos'),
  setPos: (x,y) => ipcRenderer.send('set-pos', x, y),
  resize: (w,h) => ipcRenderer.send('resize', w, h),
  minimize: () => ipcRenderer.invoke('minimize'),
  close: () => ipcRenderer.invoke('close'),
  setApiKey: (k) => ipcRenderer.invoke('set-api-key', k),
  getApiKey: () => ipcRenderer.invoke('get-api-key'),
  setMic: (on) => ipcRenderer.invoke('set-mic', on),
  listMics: () => ipcRenderer.invoke('list-mics'),
  setMicDevice: (dev) => ipcRenderer.invoke('set-mic-device', dev),
  getMicDevice: () => ipcRenderer.invoke('get-mic-device'),
  getSpeech: () => ipcRenderer.invoke('get-speech'),
  setSpeechMode: (mode) => ipcRenderer.invoke('set-speech-mode', mode),
  setPttContext: (ctx) => ipcRenderer.send('ptt-context', ctx),
  onPttState: (cb) => { ipcRenderer.on('ptt-state', (e, st) => cb(st)); },
  input: (cmd) => ipcRenderer.invoke('agent-input', cmd),
  screenInfo: () => ipcRenderer.invoke('screen-info'),
  foregroundInfo: () => ipcRenderer.invoke('foreground-info'),
  restoreFocus: () => ipcRenderer.invoke('restore-focus'),
  openApp: (name) => ipcRenderer.invoke('open-app', name),
  openUrl: (url) => ipcRenderer.invoke('open-url', url),
  stopRequested: () => ipcRenderer.invoke('stop-requested'),
  clearStop: () => ipcRenderer.invoke('clear-stop'),
  hotkeyLabels: () => ipcRenderer.invoke('hotkey-labels'),
  runArtifact: (msg) => ipcRenderer.invoke('run-artifact', msg),
  imageDiff: (msg) => ipcRenderer.invoke('image-diff', msg),
  annotateCrop: (msg) => ipcRenderer.invoke('annotate-crop', msg),
  enterActive: () => ipcRenderer.invoke('enter-active'),
  leaveActive: () => ipcRenderer.invoke('leave-active'),
  setIgnoreMouse: (ig) => ipcRenderer.invoke('set-ignore-mouse', ig),
  toSimplified: (t) => { if(!_cnv) return String(t); try { return _cnv(String(t)); } catch(e) { return String(t); } },
});